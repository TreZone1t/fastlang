#include "math.h"
#include <math.h>

double fast_sqrt(double x) {
    return sqrt(x);
}

double fast_pow(double base, double exp) {
    return pow(base, exp);
}

double fast_sin(double x) {
    return sin(x);
}

double fast_cos(double x) {
    return cos(x);
}

double fast_tan(double x) {
    return tan(x);
}
